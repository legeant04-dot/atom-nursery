/**
 * tools/test_icon_set.js — ชุดไอคอนของแอป ต้องเป็น "ชุด" ไม่ใช่กองของที่เก็บมาเรื่อย ๆ
 *   node tools/test_icon_set.js
 *
 * ───────────────────────────────────────────────────────────────────────────────────────────────
 * UI_AUDIT §2.6: emoji **173 แบบ ใช้ 1,619 ครั้ง** และ 31 แบบใช้ครั้งเดียวทั้งแอป
 * **173 ไม่ใช่ชุดไอคอน — มันคือการไม่มีชุดไอคอน** · และ emoji วาดไม่เหมือนกันบน Android
 * ทุกยี่ห้อ ซึ่งแปลว่า **แบรนด์ของโรงเรียนเปลี่ยนไปตามรุ่นมือถือของผู้ปกครอง**
 *
 * 🔴 แต่คำตอบไม่ใช่ "เอา emoji ออกให้หมด" · วัดแล้วแยกได้สองกอง:
 *   · คำกริยา (แก้ไข ลบ บันทึก เพิ่ม ปิด ค้นหา) = ไอคอน ซ้ำทุกหน้าจอ → เป็นชุดของเรา
 *   · คำนาม/สถานะ (👶 เด็ก · 🏫 โรงเรียน · 🏖️ ลา · 🎉 OT วันหยุด · 💉 วัคซีน · 🚑 อุบัติเหตุ)
 *     = สื่อความหมาย ไม่ใช่ปุ่ม และผู้ปกครองชอบ → เก็บไว้
 *
 * **"เก็บความอบอุ่นไว้ ตัดคำศัพท์ลง"** ไม่ใช่ "ทำให้ทุกอย่างเป็นเส้นสีเทา"
 */
const fs = require('fs'), path = require('path');
let pass = 0, fail = 0;
function ok_(label, cond) { console.log((cond ? '  ok   ' : '  FAIL ') + label); cond ? pass++ : fail++; }
function eq(label, got, want) {
  const okk = JSON.stringify(got) === JSON.stringify(want);
  console.log((okk ? '  ok   ' : '  FAIL ') + label + '  got=' + JSON.stringify(got) + (okk ? '' : ' want=' + JSON.stringify(want)));
  okk ? pass++ : fail++;
}
const R = f => fs.readFileSync(path.join(__dirname, '..', f), 'utf8').replace(/\r\n/g, '\n');
const appAll = R('webapp/app.js'), css = R('webapp/styles.css');
const CUT = appAll.indexOf('function buildReceiptHTML');
const app = appAll.slice(0, CUT), paper = appAll.slice(CUT);
const ICON_SRC = app.slice(app.indexOf('const ICON = {'), app.indexOf('window.svgIcon ='));
const NAMES = (ICON_SRC.match(/^\s{4}(\w+):'/gm) || []).map(s => s.trim().replace(":'", ''));

console.log('1) 🎨 ชุดไอคอนเป็นของเราเอง ไม่ใช่ไลบรารีของใคร');
{
  /* 🔴 ถามให้แคบลงกว่าที่เขียนครั้งแรก · ตอนแรกถามว่า "ทั้งไฟล์ไม่มีคำว่า cdn" ซึ่งแดงทันที
   * เพราะ SDK ของ LINE อยู่ที่ line-scdn.net และฟีเจอร์อัปโหลดฟอนต์ใบประกาศพูดถึง .ttf
   * ทั้งสองไม่เกี่ยวกับไอคอนเลย — ข้ออ้างจริงคือ **ชุดไอคอนไม่พึ่งของข้างนอก** ไม่ใช่ทั้งแอป */
  ok_('ทุกตัวเป็นเส้นบนตาราง 24×24 ของเราเอง',
    /viewBox="0 0 24 24"/.test(app) && !/cdn|unpkg|fontawesome|material-icons|iconify/i.test(ICON_SRC));
  /* currentColor คือสิ่งที่ทำให้โหมดมืดและ "สีตามโรงเรียน" ได้มาฟรี — ไอคอนที่ฝังสีไว้ในตัว
   * จะต้องมีชุดที่สองสำหรับโหมดมืด ซึ่งคือจุดที่ชุดไอคอนเริ่มแตกออกจากกัน */
  ok_('🔴 ใช้ currentColor จึงตามธีมและสีโรงเรียนได้เอง', /stroke="currentColor"/.test(app));
  ok_('ไม่ต้องโหลดไฟล์เพิ่มแม้แต่ไบต์เดียว',
    !/\.woff|\.ttf|icons?\.svg|url\(/i.test(ICON_SRC) && /^\s{4}\w+:'M/m.test(ICON_SRC));
  ok_('มีสองทาง: ไอคอนเดี่ยว (แถบเมนู) และไอคอนข้างตัวหนังสือ (ปุ่ม/หัวข้อ)',
    /window\.svgIcon = \(name, size\)/.test(app) && /window\.ic = \(name, size\)/.test(app));
  /* ไทยมีสระบน — ไอคอนที่ไม่ได้วางบนเส้นฐานเดียวกันจะลอยสูงกว่าคำที่มันนำหน้าเสมอ */
  ok_('🔴 ...ตัวที่อยู่ข้างตัวหนังสือ นั่งบนเส้นฐานเดียวกับอักษรไทย',
    /\.ii\{display:inline-block;vertical-align:-\.18em/.test(css));
}

console.log('\n2) 📏 เป็น "ชุด" จริง — ไม่ใช่สองคำที่แปลว่าเรื่องเดียวกัน');
{
  ok_('มีไอคอนพอใช้งานทั้งแอป (' + NAMES.length + ' ชื่อ)', NAMES.length >= 35 && NAMES.length <= 60);
  eq('🔴 ไม่มีชื่อซ้ำกันในชุด', NAMES.length - new Set(NAMES).size, 0);
  /* ของเดิมพิสูจน์ตัวเองว่าไม่ใช่ชุด: 🔍 กับ 🔎 แปลว่าค้นหาเหมือนกัน (7+7 ครั้ง)
   * และ 📅 🗓️ 📆 คือปฏิทินสามแบบ (11+7+1) · ตอนนี้เหลืออย่างละหนึ่ง */
  ['search', 'calendar', 'money', 'chart'].forEach(n =>
    ok_('...มี ' + n + ' เพียงตัวเดียว', NAMES.filter(x => x === n).length === 1));
  ok_('ทุกเส้นทางใช้ตัวสร้างเดียวกัน ไม่มีใครวาด <svg> เองนอกชุด',
    (app.match(/<svg class="(i|ii)"/g) || []).length === 2);
}

console.log('\n3) 🔁 คำกริยาย้ายมาเป็นไอคอนแล้ว');
{
  const n = (app.match(/\$\{ic\('/g) || []).length;
  ok_('ถูกใช้งานจริงหลายร้อยจุด (ได้ ' + n + ')', n >= 250);
  /* ตำแหน่ง "ไอคอน" คือต้นข้อความของปุ่ม/หัวข้อเท่านั้น · emoji กลางประโยคคือเนื้อหา */
  const VERBS = ['✏️', '🗑️', '💾', '➕', '👁️', '🔗', '📤', '♻️', '🔄', '🖼️', '🚫', '🔍', '🔎', '📎', '🖨️'];
  const left = VERBS.filter(e => new RegExp('(<button[^>]*>|<h3[^>]*>|<summary[^>]*>)\\s*(?:\\$\\{[^{}]*\\}\\s*)?' + e).test(app));
  eq('🔴 ไม่มีคำกริยาเหลือเป็น emoji ในตำแหน่งไอคอนแล้ว', left, []);
}

console.log('\n3b) 🧰 แถวปุ่มเครื่องมือ — ใส่เครื่องแบบเดียวกันทั้งแถว (ผอ. เลือกข้อ ค)');
{
  /* 🔴 กฎ "คำกริยา/คำนาม" ถูกต้องในระดับทั้งแอป แต่ในแถวของปุ่มเจ็ดปุ่มที่ทำหน้าที่เหมือนกัน
   * (เป็นประตูไปเครื่องมือ) ความสม่ำเสมอของเครื่องหมายสำคัญกว่า — ผอ. ตัดสิน 2026-10-28 */
  /* ตัดด้วย "ถึงวงเล็บปิดที่สมดุล" ไม่ใช่ regex ขี้เกียจ — รายการข้างในมี ]) ของตัวเองอยู่
   * (ครั้งแรกเขียนแบบ non-greedy แล้วมันหยุดที่ตัวแรก ชุดเลยผ่านเพราะไม่ได้อ่านอะไรเลย) */
  const rows = [];
  for (let i = app.indexOf('opTools(['); i > -1; i = app.indexOf('opTools([', i + 1)) {
    let d = 0, j = i + 8;
    for (; j < app.length; j++) { const c = app[j];
      if (c === '[' || c === '(') d++; else if (c === ']' || c === ')') { d--; if (!d) break; } }
    rows.push(app.slice(i, j + 1));
  }
  /* สองแถว: แท็บคุณครู และแท็บนักเรียน ของหน้า "ดำเนินการ" — นับจากของจริง ไม่ใช่เดา */
  ok_('มีแถวปุ่มเครื่องมืออยู่จริง (' + rows.length + ' แถว)', rows.length === 2);
  const stray = rows.join('\n').match(/\['[^a-z'][^']*',/g) || [];
  eq('🔴 ไม่เหลือ emoji ในแถวเครื่องมือแล้ว', stray, []);
  /* ป้ายบางอันพก emoji มาในตัว (t('ot.adminOT') = "⏰ OT คุณครู") — วาดไอคอนแล้วพิมพ์ป้ายทั้งก้อน
   * = เครื่องหมายสองอันเรียงกัน · เห็นบนหน้าจอจริง ไม่เห็นจากการอ่านโค้ด */
  ok_('🔴 ...และป้ายที่พก emoji มาเอง ถูกตัดออกก่อนวาด', /esc\(svg\?stripIc\(L\):L\)/.test(app));
  ok_('...ด้วยตัวตัดตัวเดียวกับอีกแถวหนึ่ง ไม่ใช่สำเนาที่สอง',
    (app.match(/const stripIc/g) || []).length === 1);
}

console.log('\n4) 🧸 แต่ความอบอุ่นยังอยู่ — คำนามและสถานะไม่ถูกแตะ');
{
  /* 🔴 ครึ่งที่เสียง่ายที่สุด · ถ้าแปลงทุก emoji เป็นเส้นสีเทา แอปจะ "เป็นระเบียบขึ้น"
   * และ **เป็นมิตรน้อยลง** ซึ่งสวนทางกับจุดประสงค์ของ Phase 3 ทั้งหมด */
  const KEEP = { '👶': 'เด็ก', '🏫': 'โรงเรียน', '🏖️': 'ลา', '🎉': 'OT วันหยุด',
                 '💉': 'วัคซีน', '🚑': 'อุบัติเหตุ', '🎓': 'จบการศึกษา', '🍚': 'อาหาร' };
  Object.keys(KEEP).forEach(e => ok_('ยังมี ' + e + ' (' + KEEP[e] + ')', app.indexOf(e) > -1));
  ok_('...และเหตุผลที่เก็บไว้ถูกเขียนไว้ข้างชุดไอคอน', /ผู้ปกครองชอบ/.test(app));
}

console.log('\n5) 📄 กระดาษไม่ถูกแตะ');
{
  /* เอกสารที่พิมพ์ถูกเปิดในแท็บของตัวเอง ไม่มี styles.css ของแอป — ไอคอนที่อ้าง currentColor
   * หรือคลาสของเรา จะกลายเป็นของที่ไม่มีอยู่จริงบนกระดาษ */
  ok_('ไม่มีไอคอนของหน้าจอหลุดเข้าไปในใบเสร็จ/สลิป', !/\$\{ic\('/.test(paper) && !/svgIcon\(/.test(paper));
}

console.log('\n' + (fail ? 'FAILED ' : 'PASSED ') + pass + ' passed, ' + fail + ' failed\n');
process.exit(fail ? 1 : 0);
