/**
 * tools/pg_sync_schema.js — bring the staging database up to the generated schema.
 *   node tools/pg_sync_schema.js            say what differs, change nothing
 *   node tools/pg_sync_schema.js --apply    do it
 *
 * 🔴 WHY THIS EXISTS. Phase 2.3 ran the suites against staging and found the database and
 * docs/schema/001_init.sql had drifted apart with nothing to notice:
 *
 *   · `student_terms` was in the file and NOT in the database, because the file declares columns
 *     called `from` and `to` — reserved words — so that one `create table` was a syntax error while
 *     the other fifty-four ran. A file applied with `on_error_stop` off loses statements quietly.
 *   · 48 unique indexes had been generated by guessing the row key from a column name, and 13 of
 *     them asserted things like "one check-in per teacher, ever".
 *
 * The schema file is the source of truth; this makes the database match it. It only ever ADDS what
 * is missing and DROPS indexes the generator no longer emits — it will not drop a table or a column,
 * because on the day this is pointed at production that must not be a thing it can do.
 */
const fs = require('fs'), path = require('path');
const { connect } = require('./pg_lib');

const SQL = path.join(__dirname, '..', 'docs', 'schema', '001_init.sql');
const APPLY = process.argv.includes('--apply');

/** Split the file into statements.
 *
 * 🔴 DOLLAR-QUOTE AWARE, which the first version was not. Splitting on `;` tore the RLS block —
 * `do $$ … $f$ … $$` — into four fragments, each of which failed, and the run reported "253 ok, 4
 * failed" while the thing that had not run was ROW-LEVEL SECURITY on a brand-new table. A tool that
 * repairs schema drift must not be capable of introducing the one kind of drift that matters.
 */
function statements(sql) {
  const out = [];
  let buf = '', i = 0, tag = null;
  const src = sql.replace(/^\s*--.*$/gm, '');
  while (i < src.length) {
    if (tag) {
      if (src.startsWith(tag, i)) { buf += tag; i += tag.length; tag = null; continue; }
      buf += src[i++]; continue;
    }
    const m = /^\$[A-Za-z_]*\$/.exec(src.slice(i));
    if (m) { tag = m[0]; buf += tag; i += tag.length; continue; }
    if (src[i] === ';') { if (buf.trim()) out.push(buf.trim()); buf = ''; i++; continue; }
    buf += src[i++];
  }
  if (buf.trim()) out.push(buf.trim());
  return out;
}

(async () => {
  const { client: c, scrub } = await connect();
  const sql = fs.readFileSync(SQL, 'utf8').replace(/\r\n/g, '\n');
  const sts = statements(sql);

  // ── what the file says should exist ───────────────────────────────────────────────────────────
  const wantTables = new Set();
  const wantUq = new Map();          // name → the columns it is on
  sts.forEach(s => {
    let m = /^create table if not exists (\w+)/.exec(s); if (m) wantTables.add(m[1]);
    /* 🔴 THE COLUMNS, NOT JUST THE NAME. The first version of this compared names, and reported
     * `student_charges_code_uq` as present and correct — while the live one was on student_id and
     * the file now says charge_id. An index that keeps its name and changes its meaning is exactly
     * the drift this tool exists to catch, and it was invisible for one draft. */
    m = /^create unique index if not exists (\w+) on \w+\(([^)]*)\)/.exec(s);
    if (m) wantUq.set(m[1], m[2].replace(/["\s]/g, ''));
  });

  const have = await c.query("select table_name from information_schema.tables where table_schema='public'");
  const haveTables = new Set(have.rows.map(r => r.table_name));
  const haveIdx = await c.query("select indexname, indexdef from pg_indexes where schemaname='public' and indexname like '%_code_uq'");
  const haveUq = new Map();
  haveIdx.rows.forEach(r => {
    const m = /\(([^)]*)\)\s*$/.exec(r.indexdef);
    haveUq.set(r.indexname, m ? m[1].replace(/["\s]/g, '') : '?');
  });

  /* 🔴 AND THE COLUMNS. `create table if not exists` does nothing at all to a table that already
   * exists, so seven columns added to OT_DAILY on 2026-10-13 — every OT discount and the reason for
   * every cancelled charge — were in the file and absent from the database, which is the same shape
   * of drift as the missing table and just as quiet. Adding a column is safe; this tool still never
   * drops or retypes one, because on the day it is pointed at production that must not be a thing
   * it can do. A type that CHANGED is reported and left alone, for a reviewed migration to handle. */
  const wantCols = {};
  sts.forEach(s => {
    const m = /^create table if not exists (\w+) \(([\s\S]*)\)$/.exec(s);
    if (!m) return;
    wantCols[m[1]] = {};
    for (const c of m[2].matchAll(/^\s+"?([a-z_]+)"?\s+([a-z0-9_(), ]+?),?\s*$/gm))
      if (!/^(id|seq|tenant_id)$/.test(c[1])) wantCols[m[1]][c[1]] = c[2].trim();
  });
  const haveCols = {};
  const hc = await c.query("select table_name, column_name, data_type from information_schema.columns where table_schema='public'");
  hc.rows.forEach(r => { (haveCols[r.table_name] = haveCols[r.table_name] || {})[r.column_name] = r.data_type; });
  const missingCols = [];
  Object.keys(wantCols).forEach(t => {
    if (!haveTables.has(t)) return;             // the whole table is missing; it is created below
    Object.keys(wantCols[t]).forEach(col => {
      if (!haveCols[t] || !haveCols[t][col]) missingCols.push({ t, col, type: wantCols[t][col] });
    });
  });

  const missingTables = [...wantTables].filter(t => !haveTables.has(t));
  // stale = the file no longer wants it at all, OR wants it on different columns
  const staleUq = [...haveUq.keys()].filter(i => !wantUq.has(i) || wantUq.get(i) !== haveUq.get(i));
  const missingUq = [...wantUq.keys()].filter(i => !haveUq.has(i) || wantUq.get(i) !== haveUq.get(i));

  console.log('\n=== staging vs docs/schema/001_init.sql ===\n');
  console.log('  ตารางในไฟล์            ' + wantTables.size);
  console.log('  ตารางในฐานข้อมูล        ' + [...wantTables].filter(t => haveTables.has(t)).length);
  console.log('  🔴 ตารางที่ขาด          ' + missingTables.length + (missingTables.length ? '  ' + missingTables.join(' ') : ''));
  console.log('  🔴 คอลัมน์ที่ขาด        ' + missingCols.length +
    (missingCols.length ? '\n     ' + missingCols.map(x => x.t + '.' + x.col + ' ' + x.type).join('\n     ') : ''));
  const show = n => n + (haveUq.has(n) ? '  (ตอนนี้: ' + haveUq.get(n) + ')' : '') +
    (wantUq.has(n) ? '  → ' + wantUq.get(n) : '  → ไม่ควรมี');
  console.log('  🔴 unique index ที่ผิด   ' + staleUq.length + (staleUq.length ? '\n     ' + staleUq.map(show).join('\n     ') : ''));
  console.log('  unique index ที่ต้องสร้าง ' + missingUq.length + (missingUq.length ? '\n     ' + missingUq.map(show).join('\n     ') : ''));

  if (!APPLY) {
    console.log('\n(ยังไม่ได้แก้ — ใส่ --apply เพื่อดำเนินการ)\n');
    await c.end(); return;
  }

  console.log('\n--- applying ---');
  /* The wrong indexes go FIRST. One of them is on a table that is about to receive rows it would
   * refuse, and leaving it in place while the rest runs is how a half-applied schema is made. */
  for (const i of staleUq) {
    await c.query('drop index if exists ' + i);
    console.log('  dropped  ' + i);
  }
  for (const x of missingCols) {
    await c.query('alter table ' + x.t + ' add column if not exists "' + x.col + '" ' + x.type);
    console.log('  added    ' + x.t + '.' + x.col + ' ' + x.type);
  }
  /* Every statement, in file order, each one its own transaction and each failure REPORTED. The
   * drift being repaired here happened because a run like this once swallowed an error. */
  let ran = 0, failed = 0;
  for (const s of sts) {
    try { await c.query(s); ran++; }
    catch (e) {
      failed++;
      console.log('  🔴 ' + scrub(e.message) + '\n     ' + s.split('\n')[0].slice(0, 90));
    }
  }
  console.log('  ' + ran + ' statements ok, ' + failed + ' failed');

  const after = await c.query("select table_name from information_schema.tables where table_schema='public'");
  const afterIdx = await c.query("select indexname from pg_indexes where schemaname='public' and indexname like '%_code_uq'");
  console.log('\n  ตาราง ' + after.rows.length + ' · unique code index ' + afterIdx.rows.length);
  const stillMissing = [...wantTables].filter(t => !after.rows.some(r => r.table_name === t));
  console.log('  ' + (stillMissing.length ? '🔴 ยังขาด: ' + stillMissing.join(' ') : '✅ ครบตามไฟล์') + '\n');
  await c.end();
  process.exit(failed ? 1 : 0);
})().catch(e => { console.error(String(e && e.message || e)); process.exit(1); });
