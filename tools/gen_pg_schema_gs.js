/**
 * tools/gen_pg_schema_gs.js — writes src/PgSchema.gs, the sheet ⇄ table map Apps Script needs
 *   node tools/gen_pg_schema_gs.js            (write)
 *   node tools/gen_pg_schema_gs.js --check    (exit 1 if src/PgSchema.gs is out of date)
 *
 * Week 2 of docs/SPEED_FIRST_PLAN.md: Apps Script reads and writes Postgres through src/DbPg.gs.
 * Apps Script cannot read docs/schema/001_init.sql at run time, so the mapping is GENERATED from the
 * same three declarations the SQL itself came from — src/Config.gs SCHEMA (which columns, in which
 * order), the generated SQL (which type), and pg_migrate's tableFor (which table) — and checked in.
 * Typing it by hand would be a fourth copy of the schema, and the one that drifts.
 *
 * Shape:  PG_SCHEMA_['MAIN:STUDENTS'] = { t: 'students', c: [ ['StudentID','student_id','text'], … ] }
 *         keyed by WORKBOOK as well as sheet, because MAIN and HR both have an AUDIT_LOG.
 */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const R = f => fs.readFileSync(path.join(ROOT, f), 'utf8').replace(/\r\n/g, '\n');
const { targetSchema } = require('./pg_migrate.js');

const decomment = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
const snake = s => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/[^A-Za-z0-9]+/g, '_').toLowerCase();
const HR_PREFIXED = new Set(['AUDIT_LOG']);
const tableFor = (wb, sheet) => (wb === 'HR' && HR_PREFIXED.has(sheet)) ? 'hr_' + snake(sheet) : snake(sheet);

function build() {
  const cfg = decomment(R('src/Config.gs'));
  const types = targetSchema();
  const out = {};
  for (const wb of ['MAIN', 'HR']) {
    const start = cfg.indexOf(`SCHEMA[WB.${wb}] = {`); if (start < 0) continue;
    const end = cfg.indexOf('\n};', start);
    const block = cfg.slice(start, end < 0 ? undefined : end);
    for (const m of block.matchAll(/^\s{2}([A-Z][A-Z0-9_]*):\s*\[([\s\S]*?)\],?\s*$/gm)) {
      const sheet = m[1], table = tableFor(wb, sheet);
      if (!types[table]) continue;                        // declared in Config but no table — reported by the check
      const cols = [...new Set((m[2].match(/'([^']+)'/g) || []).map(s => s.slice(1, -1)))];
      out[wb + ':' + sheet] = { t: table, c: cols.filter(c => types[table][snake(c)]).map(c => [c, snake(c), types[table][snake(c)]]) };
    }
  }
  return out;
}

function render(map) {
  const lines = Object.keys(map).sort().map(k => '  ' + JSON.stringify(k) + ': ' + JSON.stringify(map[k]));
  return [
    '/**',
    ' * PgSchema.gs — GENERATED by tools/gen_pg_schema_gs.js. Do not edit by hand.',
    ' * Which sheet is which Postgres table, and each column\'s name and type there. Read by DbPg.gs.',
    ' * Regenerate after any change to SCHEMA in Config.gs or to docs/schema/001_init.sql.',
    ' */',
    'var PG_SCHEMA_ = {',
    lines.join(',\n'),
    '};',
    ''
  ].join('\n');
}

const text = render(build());
const target = path.join(ROOT, 'src', 'PgSchema.gs');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== text) { console.error('src/PgSchema.gs is out of date — run: node tools/gen_pg_schema_gs.js'); process.exit(1); }
  console.log('src/PgSchema.gs is in step'); process.exit(0);
}
fs.writeFileSync(target, text);
console.log('src/PgSchema.gs written — ' + Object.keys(build()).length + ' sheets');
